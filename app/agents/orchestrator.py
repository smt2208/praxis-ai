async def follow_up_node(state: OrchestratorState) -> dict:
    """Direct Conversational Follow-Up Node: Direct answers without tool overhead."""
    writer = get_stream_writer()
    if writer:
        writer({"event": "agent_start", "data": {"agent": "follow_up", "message": "Thinking..."}})

    recent_msgs = state["messages"][-10:] if len(state["messages"]) > 10 else state["messages"]
    followup_messages = [SystemMessage(content=FOLLOW_UP_SYSTEM)] + recent_msgs + [HumanMessage(content=state["query"])]

    tokens = []
    async for chunk in _followup_llm.astream(followup_messages):
        content = chunk.content
        if isinstance(content, str) and content:
            tokens.append(content)
            if writer:
                writer({"event": "token", "data": {"agent": "follow_up", "content": content}})
        elif isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and block.get("type") == "text" and block.get("text"):
                    tokens.append(block["text"])
                    if writer:
                        writer({"event": "token", "data": {"agent": "follow_up", "content": block["text"]}})

    return {"final_answer": "".join(tokens)}


