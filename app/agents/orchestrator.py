async def hybrid_node(state: OrchestratorState) -> dict:
    """
    Hybrid Fan-Out Node:
    Runs two departments concurrently (e.g. knowledge_team + research_team) and
    synthesizes a unified response streamed to the client.
    """
    writer = get_stream_writer()
    if writer:
        writer({"event": "agent_start", "data": {
            "agent": "hybrid",
            "message": "Searching documents and live web in parallel...",
        }})

    primary_route = state.get("route", "knowledge_team")
    secondary_route = state.get("secondary_route", "general")

    async def _run_department(route: str) -> str:
        if route == "knowledge_team":
            parts = []
            async for evt in astream_knowledge_team(
                state["query"],
                user_id=state["user_id"],
                conversation_id=state["conversation_id"],
                history=state["messages"],
                collect_context=False,
            ):
                if evt.get("type") == "token":
                    parts.append(evt["content"])
            return "".join(parts)
        elif route == "general":
            parts = []
            async for token in astream_general_agent(state["query"], state["messages"], user_tz=state.get("user_tz")):
                parts.append(token)
            return "".join(parts)
        elif route == "research_team":
            parts = []
            async for evt in astream_research_team(state["query"], history=state["messages"]):
                if evt.get("type") == "token":
                    parts.append(evt["content"])
            return "".join(parts)
        return ""

    primary_result, secondary_result = await asyncio.gather(
        _run_department(primary_route),
        _run_department(secondary_route),
        return_exceptions=True,
    )

    if isinstance(primary_result, Exception):
        logger.error("[Hybrid] Primary route failed: %s", primary_result)
        primary_result = ""
    if isinstance(secondary_result, Exception):
        logger.error("[Hybrid] Secondary route failed: %s", secondary_result)
        secondary_result = ""

    if writer:
        writer({"event": "agent_start", "data": {"agent": "hybrid", "message": "Synthesizing findings..."}})

    synth_prompt = (
        f"USER QUERY:\n{state['query']}\n\n"
        f"--- DOCUMENT INTELLIGENCE ({primary_route}) ---\n{primary_result}\n\n"
        f"--- WEB / RESEARCH INTELLIGENCE ({secondary_route}) ---\n{secondary_result}\n\n"
        "Synthesize both into one cohesive, well-structured answer."
    )
    tokens = []
    async for chunk in _synthesizer_llm.astream([
        SystemMessage(content=MULTI_AGENT_SYNTHESIZER_SYSTEM),
        HumanMessage(content=synth_prompt),
    ]):
        content = chunk.content
        if isinstance(content, str) and content:
            tokens.append(content)
            if writer:
                writer({"event": "token", "data": {"agent": "hybrid", "content": content}})
        elif isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and block.get("type") == "text" and block.get("text"):
                    tokens.append(block["text"])
                    if writer:
                        writer({"event": "token", "data": {"agent": "hybrid", "content": block["text"]}})

    return {"final_answer": "".join(tokens)}


# ---------------------------------------------------------------------------
# LangGraph Graph Assembly & Compilation
# ---------------------------------------------------------------------------

def _build_orchestrator_graph():
    """
    Compile the top-level LangGraph state graph.
    Adding future agent departments requires only:
      1. Defining a new agent node function
      2. builder.add_node("new_agent", new_agent_node)
      3. Adding the branch in select_route and builder.add_edge("new_agent", END)
    """
    builder = StateGraph(OrchestratorState)

    builder.add_node("ceo_router", ceo_router_node)
    builder.add_node("knowledge_team", knowledge_team_node)
    builder.add_node("research_team", research_team_node)
    builder.add_node("general", general_agent_node)
    builder.add_node("vision_agent", vision_agent_node)
    builder.add_node("follow_up", follow_up_node)
    builder.add_node("hybrid", hybrid_node)

    builder.add_edge(START, "ceo_router")
    builder.add_conditional_edges(
        "ceo_router",
        select_route,
        {
            "knowledge_team": "knowledge_team",
            "research_team": "research_team",
            "general": "general",
            "vision_agent": "vision_agent",
            "follow_up": "follow_up",
            "hybrid": "hybrid",
        },
    )

    for node_name in ["knowledge_team", "research_team", "general", "vision_agent", "follow_up", "hybrid"]:
        builder.add_edge(node_name, END)

    return builder.compile()


orchestrator_graph = _build_orchestrator_graph()


# ---------------------------------------------------------------------------
# Public streaming entry point (called by chat_stream service)
# ---------------------------------------------------------------------------

@traceable(name="Orchestrator SSE Stream", run_type="chain")
async def astream_graph_events(
    query: str,
    history: list[dict],
    user_id: str,
    conversation_id: str,
    has_documents: bool,
    images: list[str] | None = None,
    user_tz: str | None = None,
    memory_enabled: bool = True,
    user_profile: dict | None = None,
):
    """
    Async generator for real-time Server-Sent Events (SSE) streaming powered by LangGraph.

    Execution model:
      1. Converts raw message history dicts into LangChain BaseMessage instances.
      2. Retrieves long-term user memories via Mem0 (offloaded via asyncio.to_thread).
      3. Constructs combined user profile & memory context as the leading SystemMessage.
      4. Initializes OrchestratorState and invokes orchestrator_graph.astream() with stream_mode="custom".
      5. Nodes emit SSE events ('agent_start', 'token') in real-time via LangGraph's get_stream_writer().
      6. Yields a final terminal event {"event": "done", "data": {"route": ...}} with execution metadata.
    """
    messages = _history_to_messages(history)
    img_list = images or []

    # Mem0 memory lookup is blocking I/O; run in thread pool to prevent event loop stalls
    memory_context = (await asyncio.to_thread(retrieve_memories, user_id, query)) if memory_enabled else ""
    profile_context = build_user_profile_context(user_profile)

    combined_context = "\n\n".join(filter(None, [profile_context, memory_context]))
    if combined_context:
        messages.insert(0, SystemMessage(content=combined_context))

    initial_state: OrchestratorState = {
        "messages": messages,
        "query": query,
        "user_id": user_id,
        "conversation_id": conversation_id,
        "has_documents": has_documents,
        "images": img_list,
        "user_tz": user_tz,
        "route": "",
        "secondary_route": "",
        "is_hybrid": False,
        "final_answer": "",
    }

    executed_route = "general"
    # Stream mode "custom" allows subgraphs and node functions to yield domain events via get_stream_writer()
    async for evt in orchestrator_graph.astream(initial_state, stream_mode="custom"):
        if isinstance(evt, dict):
            # Capture the executing specialist department for frontend metadata
            if evt.get("event") == "agent_start" and evt.get("data", {}).get("agent"):
                ag = evt["data"]["agent"]
                if ag not in ("ceo",):
                    executed_route = ag
            yield evt

    # Final event signaling complete transmission of the response stream
    yield {"event": "done", "data": {"route": executed_route}}
