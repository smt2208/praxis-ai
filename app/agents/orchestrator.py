"""
app/agents/orchestrator.py

LangGraph Multi-Agent Orchestrator.
Uses a declarative StateGraph to coordinate the CEO router and specialized agent teams,
streaming real-time Server-Sent Events (SSE) via LangGraph's custom streaming mode.
"""
import logging
import asyncio
from typing import TypedDict

from langchain_openai import ChatOpenAI
from langchain_core.messages import BaseMessage, HumanMessage, AIMessage, SystemMessage
from langgraph.graph import StateGraph, START, END
from langgraph.config import get_stream_writer
from langsmith import traceable

from app.config import DEFAULT_MODEL
from app.agents.context import format_history, build_doc_context, build_image_context, build_user_profile_context
