logger = logging.getLogger(__name__)

_followup_llm = ChatOpenAI(model=DEFAULT_MODEL, temperature=0.7)
_synthesizer_llm = ChatOpenAI(model=DEFAULT_MODEL, temperature=0)


# ---------------------------------------------------------------------------
# History conversion helper
# ---------------------------------------------------------------------------

def _history_to_messages(history: list[dict]) -> list[BaseMessage]:
    """Convert list of {"role": ..., "content": ...} dicts to LangChain BaseMessage objects."""
    result: list[BaseMessage] = []
    for msg in history:
        if msg["role"] == "user":
            result.append(HumanMessage(content=msg["content"]))
        else:
            result.append(AIMessage(content=msg["content"]))
    return result


# ---------------------------------------------------------------------------
# LangGraph Orchestrator State Definition
# ---------------------------------------------------------------------------

class OrchestratorState(TypedDict):
    """
    Typed state dictionary passed across nodes in the LangGraph multi-agent graph.

    Fields:
      messages:        Current conversation history converted into LangChain BaseMessage objects.
      query:           Latest user query text.
      user_id:         Authenticated user UUID for resource isolation.
      conversation_id: Active conversation UUID for per-session document scoping.
      has_documents:   Flag indicating whether documents have been ingested for this conversation.
      images:          Optional list of base64 data URIs for vision analysis.
      user_tz:         Client timezone string (e.g., 'America/New_York') for temporal grounding.
      route:           Primary destination selected by the CEO router.
      secondary_route: Secondary destination for hybrid queries (e.g., docs + live web).
      is_hybrid:       True if parallel multi-department fan-out was requested.
      final_answer:    Consolidated markdown answer generated by the executed agent team.
    """
    messages: list[BaseMessage]
    query: str
    user_id: str
    conversation_id: str
    has_documents: bool
    images: list[str]
    user_tz: str | None
    route: str
    secondary_route: str
    is_hybrid: bool
    final_answer: str


